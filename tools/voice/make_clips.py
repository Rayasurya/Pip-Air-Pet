"""Makes Pip's spoken clips on the Mac and builds them into the firmware.

Uses the Mac's built-in `say` voice (no internet), converts each line to 8 kHz, 8-bit mono, and
writes firmware/lib/pet/voice_clips.h/.cpp. Also saves WAV previews in preview-out/voice/ so you
can listen before the speaker arrives. Speaker only: Pip has no microphone.

Run:  tools/.venv/bin/python tools/voice/make_clips.py              (voice "Aman", Indian English)
      tools/.venv/bin/python tools/voice/make_clips.py --voice Samantha
A family member's own recording can replace a clip later: put a WAV at tools/voice/custom/<id>.wav.
"""
import argparse
import subprocess
import tempfile
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
RATE = 8000

# id, words. Words only where there is something to do or to know. Moods otherwise use pet sounds.
CLIPS = [
    ("AskOk", "Are you okay? Please touch my head."),
    ("Thanks", "Thank you."),
    ("ToldFamily", "I have told your family."),
    ("Fresh", "The air is fresh."),
    ("StaleSoon", "The air is getting stale. Open a window soon."),
    ("Stale", "The air is stale. Please open a window."),
    ("VeryStale", "The air is very stale. Open a window now."),
    ("Hot", "It is too hot in here."),
    ("Dry", "The air is very dry."),
    ("Damp", "It is damp in here."),
    ("CarCheck", "Someone may still be in the car. Please check the seats."),
    ("CarHot", "The car is getting hot. Check the seats now."),
]


def render(text, voice, tmp):
    aiff, wav = Path(tmp) / "c.aiff", Path(tmp) / "c.wav"
    subprocess.run(["say", "-v", voice, "-o", str(aiff), text], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1", str(aiff), str(wav)], check=True)
    return read_wav(wav)


def read_wav(path):
    with wave.open(str(path)) as w:
        assert w.getsampwidth() == 2 and w.getnchannels() == 1 and w.getframerate() == RATE, path
        x = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32)
    nz = np.flatnonzero(np.abs(x) > 300)                      # trim silence at both ends
    if len(nz):
        x = x[max(0, nz[0] - 200): nz[-1] + 400]
    peak = np.abs(x).max() or 1
    return x / peak * 0.9                                     # normalise; volume is set on the device


def to_u8(x):
    return np.clip(np.round(x * 127 + 128), 0, 255).astype(np.uint8)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="Aman")
    a = ap.parse_args()
    lib = ROOT / "firmware" / "lib" / "pet"
    prev = ROOT / "preview-out" / "voice"
    prev.mkdir(parents=True, exist_ok=True)
    total = 0
    arrays, table = [], []
    with tempfile.TemporaryDirectory() as tmp:
        for cid, text in CLIPS:
            custom = Path(__file__).parent / "custom" / f"{cid}.wav"
            x = read_wav(custom) if custom.exists() else render(text, a.voice, tmp)
            u8 = to_u8(x)
            total += len(u8)
            with wave.open(str(prev / f"{cid}.wav"), "wb") as w:
                w.setnchannels(1), w.setsampwidth(1), w.setframerate(RATE)
                w.writeframes(u8.tobytes())
            body = ",".join(str(v) for v in u8)
            arrays.append(f"// \"{text}\"\nstatic const uint8_t k{cid}[{len(u8)}] = {{{body}}};")
            table.append(f"    {{k{cid}, {len(u8)}}},")
    h = ["// GENERATED by tools/voice/make_clips.py. Do not edit; re-run the script instead.",
         f"// Voice: macOS \"{a.voice}\" unless replaced by tools/voice/custom/<id>.wav. 8 kHz, 8-bit mono.",
         "#pragma once", "#include <stdint.h>", "",
         "enum class Clip : uint8_t {", "  " + ", ".join(c for c, _ in CLIPS) + ",", "  Count,", "  None,", "};",
         "", "struct ClipData {", "  const uint8_t* pcm;  // unsigned 8-bit, 128 = silence", "  uint32_t len;", "};",
         f"constexpr uint32_t kClipRate = {RATE};", "extern const ClipData kClipTable[(int)Clip::Count];"]
    (lib / "voice_clips.h").write_text("\n".join(h) + "\n")
    cpp = ["// GENERATED by tools/voice/make_clips.py. Do not edit; re-run the script instead.",
           '#include "voice_clips.h"', ""] + arrays + ["", "const ClipData kClipTable[(int)Clip::Count] = {"] + table + ["};"]
    (lib / "voice_clips.cpp").write_text("\n".join(cpp) + "\n")
    print(f"{len(CLIPS)} clips, {total / RATE:.1f} s, {total / 1024:.0f} KB of flash. Previews in {prev}")


if __name__ == "__main__":
    main()
